"""Live-model safe final drafting.

The model only sees the claims the approval gate let through, plus the coverage
summary. Blocked claims are never sent to the model, so any blocked content in
a live draft is a hallucination that the LLM-as-a-judge evaluation should catch.
"""

from __future__ import annotations

import json
from typing import Any

from langchain_core.runnables import RunnableLambda

from langgraph_review_workflow.model_boundary import ModelBoundaryConfig
from langgraph_review_workflow.ollama_client import OllamaClient, StructuredChatClient
from langgraph_review_workflow.schemas import (
    ClaimGroundednessCheck,
    FinalDraftResult,
    LiveDraftOutput,
)
from langgraph_review_workflow.steps.drafting import _checks_by_id, _evidence_ids_for


SYSTEM_PROMPT = """You write short, factual candidate review drafts.
Use ONLY the approved claims and the coverage summary you are given.
Do not add skills, experience, employers, numbers, or qualities that are not stated there.
Every approved claim has been verified; present each one as supported.
Do not mention claims, skills, or gaps that are not in the approved list.
Refer to the candidate by name or as "the candidate"; do not assume gender.
Cite the evidence IDs of the claims you use. Keep the draft under 150 words."""


def build_drafting_prompt(
    *,
    candidate_name: str,
    role_title: str,
    coverage_text: str,
    approved_checks: list[ClaimGroundednessCheck],
) -> str:
    approved_claims = [
        {
            "claim_id": check.claim_id,
            "claim": check.claim,
            "evidence_ids": _evidence_ids_for(check),
        }
        for check in approved_checks
    ]
    return (
        f"Candidate: {candidate_name}\n"
        f"Role: {role_title}\n"
        f"Coverage summary: {coverage_text}\n\n"
        "Approved claims:\n"
        f"{json.dumps(approved_claims, indent=2)}"
    )


def generate_safe_final_draft_live(
    payload: dict[str, Any],
    client: StructuredChatClient | None = None,
) -> FinalDraftResult:
    """Generate a draft with a live model from approved grounded claims only."""

    boundary = ModelBoundaryConfig.model_validate(payload["model_boundary"])
    client = client or OllamaClient.from_boundary(boundary)
    approval_decision = payload["approval_decision"]
    checks_by_id = _checks_by_id(
        [
            ClaimGroundednessCheck.model_validate(check)
            for check in payload.get("groundedness_checks", [])
        ]
    )
    included_claim_ids = list(approval_decision.get("approved_claim_ids", []))
    excluded_claim_ids = list(approval_decision.get("blocked_claim_ids", []))
    approved_checks = [
        checks_by_id[claim_id]
        for claim_id in included_claim_ids
        if claim_id in checks_by_id and checks_by_id[claim_id].status == "grounded"
    ]
    candidate_profile = payload.get("candidate_profile", {})
    coverage_summary = payload.get("coverage_summary", {})

    output = client.structured_chat(
        system=SYSTEM_PROMPT,
        user=build_drafting_prompt(
            candidate_name=candidate_profile.get("name", "Synthetic Candidate"),
            role_title=payload.get("role_title", "Mock Role"),
            coverage_text=coverage_summary.get("summary", "Coverage summary unavailable."),
            approved_checks=approved_checks,
        ),
        schema=LiveDraftOutput,
        temperature=boundary.temperature,
        seed=boundary.seed,
    )

    return FinalDraftResult(
        draft_text=output.draft_text,
        included_claim_ids=included_claim_ids,
        excluded_claim_ids=excluded_claim_ids,
        cited_evidence_ids=output.cited_evidence_ids,
        warnings=[
            "Synthetic demo output only; not a real job application.",
            f"Draft generated by live model {boundary.model}; review before reuse.",
        ],
    )


live_drafting_runnable = RunnableLambda(generate_safe_final_draft_live)
